#!/usr/bin/env python3
"""Build assets/dark.css, the dark theme for the IBDP Psychology site.

Run after changing assets/style.css or assets/theme.css:
    python3 tools/build_dark_css.py

The file has two parts:
  1. A hand-written part (HAND below): the dark palette for the CSS variables, plus things
     that need a decision, such as the header, doodles and charts.
  2. A generated part: every fixed colour in style.css and theme.css gets a dark version.
     Light backgrounds become dark fills in the same hue, dark text becomes light text,
     and light borders become dark borders. Strong mid-tone colours (buttons, tags) stay.
All rules only apply when settings.js sets data-theme="dark" on the page.
"""
import colorsys, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
P = 'html[data-theme="dark"]'

HAND = """/* Dark theme for the IBDP Psychology site. Generated by tools/build_dark_css.py: edit the
   hand-written part in that script, not this file. Only applies when settings.js sets
   data-theme="dark". Solid fills behind all text, soft off-white text on dark navy. */
%(P)s{
  color-scheme:dark;
  --paper:#141c23; --page:#1c262e; --bg:#141c23; --card:#1c262e; --soft:#202b34; --cloud:#212c35;
  --ink:#e4ebf0; --navy:#e4ebf0; --navy-2:#9cc8e6; --muted:#b2c0ca;
  --sky:#3e6a86; --sky-pale:#22323e; --sky-deep:#2f6f99; --sky-ink:#a9d3ee;
  --butter:#33301f; --tape-sky:rgba(80,130,160,.55); --tape-butter:rgba(150,130,80,.5);
  --pencil:#8697a3; --rule:rgba(140,190,225,.10); --margin:rgba(225,130,130,.30);
  --line:#34434e; --teal:#2f6f99; --teal-2:#a9d3ee; --teal-light:#22323e;
  --teal-dark:#a9d3ee; --rust:#d98a62; --rust-light:#3a2820; --ok:#8fd3a9;
  --c-bias:#d7a74a; --c-causality:#6cc3c3; --c-change:#7fcf99; --c-measurement:#86b6ea;
  --c-perspective:#b9a0e0; --c-responsibility:#e09a72;
}
%(P)s body{background-image:none;background-color:var(--paper);color:var(--ink);}
%(P)s header.hero,%(P)s .hero{background:#1a2630 !important;border-bottom:2px solid var(--sky);}
%(P)s .hero h1,%(P)s .hero .subtitle{text-shadow:none;}
%(P)s .doodle,%(P)s .ct svg{filter:invert(.86) hue-rotate(180deg) saturate(.8);}
%(P)s .p3-fig svg,%(P)s svg.p3-svg{background:#f4f8fb;border-radius:6px;}
%(P)s section.card,%(P)s .paper{box-shadow:0 1px 0 rgba(0,0,0,.25),0 6px 18px rgba(0,0,0,.25);}
%(P)s input,%(P)s select,%(P)s textarea{background:#18222a;color:var(--ink);border-color:#3e5260;}
%(P)s mark{background:#6b4a2e;color:#fff;}
%(P)s .chip.cc:nth-child(n){color:#fff;}
""" % {"P": P}

def parse_color(c):
    c = c.strip().lower()
    m = re.fullmatch(r"#([0-9a-f]{3}|[0-9a-f]{6})", c)
    if m:
        h = m.group(1)
        if len(h) == 3:
            h = "".join(x * 2 for x in h)
        return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)), None
    m = re.fullmatch(r"rgba?\(([^)]*)\)", c)
    if m:
        parts = [p.strip() for p in m.group(1).split(",")]
        if len(parts) >= 3:
            rgb = tuple(float(p) / 255 for p in parts[:3])
            a = float(parts[3]) if len(parts) > 3 else None
            return rgb, a
    return None, None

def fmt(rgb, a):
    r, g, b = (round(max(0, min(1, x)) * 255) for x in rgb)
    return "rgba(%d,%d,%d,%s)" % (r, g, b, ("%.2f" % a).rstrip("0").rstrip(".")) if a is not None else "#%02x%02x%02x" % (r, g, b)

def darken_bg(rgb):          # light fill -> dark fill, same hue
    h, l, s = colorsys.rgb_to_hls(*rgb)
    if l < 0.72:
        return None          # already a strong colour (button, tag): keep it
    if s < 0.12 or l > 0.985:   # white and greys take the site's navy tint
        return colorsys.hls_to_rgb(0.57, 0.145 + (1 - l) * 0.35, 0.24)
    return colorsys.hls_to_rgb(h, 0.12 + (1 - l) * 0.55, s * 0.45)

def lighten_text(rgb):       # dark text -> light text, same hue
    h, l, s = colorsys.rgb_to_hls(*rgb)
    if l > 0.5:
        return None
    return colorsys.hls_to_rgb(h, 0.84 - l * 0.25, min(s, 0.5) * 0.8)

def border(rgb):             # light border -> dark border
    h, l, s = colorsys.rgb_to_hls(*rgb)
    if l < 0.7:
        return None
    return colorsys.hls_to_rgb(h, 0.27 + (1 - l) * 0.3, s * 0.4)

COLOR_RE = re.compile(r"#[0-9a-fA-F]{3,6}\b|rgba?\([^)]*\)")

def convert(prop, value):
    if "var(" in value and not COLOR_RE.search(value):
        return None
    if prop in ("box-shadow", "text-shadow", "filter"):
        return None
    if "gradient" in value or "url(" in value:
        return None
    changed = False
    def sub(m):
        nonlocal changed
        rgb, a = parse_color(m.group(0))
        if rgb is None:
            return m.group(0)
        if prop in ("background", "background-color"):
            new = darken_bg(rgb)
        elif prop in ("color", "fill"):
            new = lighten_text(rgb)
        elif prop.startswith("border") or prop in ("outline", "stroke"):
            new = border(rgb)
        else:
            new = None
        if new is None:
            return m.group(0)
        changed = True
        return fmt(new, a)
    out = COLOR_RE.sub(sub, value)
    return out if changed else None

def strip_blocks(css, at):
    """Remove @media print and other at-rule blocks we don't want, keeping plain rules."""
    out, i = [], 0
    while True:
        j = css.find(at, i)
        if j < 0:
            out.append(css[i:]); break
        out.append(css[i:j])
        depth, k = 0, css.find("{", j)
        while k < len(css):
            if css[k] == "{": depth += 1
            elif css[k] == "}":
                depth -= 1
                if depth == 0: break
            k += 1
        i = k + 1
    return "".join(out)

rules = []
for name in ("style.css", "theme.css"):
    css = (ROOT / "assets" / name).read_text(encoding="utf-8")
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = strip_blocks(css, "@media print")
    css = re.sub(r"@media[^{]*\{", "", css)          # keep rules inside screen media queries
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        sel, body = m.group(1).strip(), m.group(2)
        if not sel or sel.startswith("@") or ":root" in sel or sel.startswith("from") or sel.startswith("to") or "%" in sel:
            continue
        decls = []
        for d in body.split(";"):
            if ":" not in d:
                continue
            prop, val = d.split(":", 1)
            prop = prop.strip().lower()
            if prop.startswith("--"):
                continue
            new = convert(prop, val.strip())
            if new:
                decls.append("%s:%s" % (prop, new))
        if decls:
            sels = ",".join("%s %s" % (P, s.strip()) if not s.strip().startswith("html") else s.strip().replace("html", P, 1)
                            for s in sel.split(","))
            rules.append("%s{%s}" % (sels, ";".join(decls)))

head, tail = HAND.split("%s body" % P, 1)          # palette first, then generated rules,
tail = "%s body" % P + tail                          # then the hand-written overrides win
out = (head + "\n/* ---- generated from style.css and theme.css ---- */\n" + "\n".join(rules) +
       "\n\n/* ---- hand-written overrides ---- */\n" + tail)
(ROOT / "assets" / "dark.css").write_text(out, encoding="utf-8")
print("assets/dark.css: %d generated rules, %d KB" % (len(rules), len(out) // 1024))
