#!/usr/bin/env python3
"""Build assets/ee-locked.js: the Extended Essay model answers, encrypted with the class code.

The model answers are kept OUTSIDE this public repository (for example in a private Drive
folder or the teacher's project files), in one HTML file with a <template id="..."> per answer.
Each id matches a <div class="ee-lock" data-lock="..."> on an EE page.

Run from the repo root:
    EE_CODE="THECODE" python3 tools/build_ee_locked.py /path/to/ee-model-answers.html

Students type the class code on any EE page. assets/ee.js derives the same key in the browser
(PBKDF2-SHA256, AES-GCM) and shows the answers. A wrong code cannot decrypt anything, and the
plain answers never appear in this repository. To change the code, run the script again with
the new code and commit assets/ee-locked.js. Codes ignore case and spaces.
"""
import base64, json, os, re, sys
from pathlib import Path
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "ee-locked.js"
ITER = 210000
CHECK = "ee-unlocked"


def b64(b):
    return base64.b64encode(b).decode("ascii")


def norm(code):
    return re.sub(r"\s+", "", code).upper()


def main():
    if len(sys.argv) != 2:
        sys.exit("Usage: EE_CODE=... python3 tools/build_ee_locked.py ANSWERS.html")
    code = norm(os.environ.get("EE_CODE", ""))
    if len(code) < 4:
        sys.exit("Set EE_CODE to the class code (at least 4 characters).")
    src = Path(sys.argv[1]).read_text(encoding="utf-8")
    blocks = dict(re.findall(r'(?s)<template id="([a-z0-9-]+)">(.*?)</template>', src))
    if not blocks:
        sys.exit("No <template id=...> blocks found.")
    for k, v in blocks.items():
        if "—" in v:
            sys.exit("Em-dash found in %s: student-facing text avoids em-dashes." % k)

    # every lock on the pages needs an answer, and every answer needs a lock
    locks = set()
    for page in ROOT.glob("ee*.html"):
        locks |= set(re.findall(r'data-lock="([a-z0-9-]+)"', page.read_text(encoding="utf-8")))
    missing, unused = sorted(locks - set(blocks)), sorted(set(blocks) - locks)
    if missing:
        sys.exit("No model answer for: " + ", ".join(missing))

    salt = os.urandom(16)
    key = PBKDF2HMAC(algorithm=hashes.SHA256(), length=32, salt=salt, iterations=ITER).derive(code.encode("utf-8"))
    aes = AESGCM(key)

    def enc(text):
        iv = os.urandom(12)
        return {"iv": b64(iv), "ct": b64(aes.encrypt(iv, text.strip().encode("utf-8"), None))}

    data = {"v": 1, "iter": ITER, "salt": b64(salt), "check": enc(CHECK),
            "blocks": {k: enc(v) for k, v in sorted(blocks.items())}}
    OUT.write_text("/* Generated by tools/build_ee_locked.py. Encrypted model answers for the EE pages:\n"
                   "   unlocked in the browser with the class code. Do not edit by hand. */\n"
                   "window.EE_LOCKED=" + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print("assets/ee-locked.js: %d answers encrypted%s" % (len(blocks), (" (not used on any page: " + ", ".join(unused) + ")") if unused else ""))


if __name__ == "__main__":
    main()
