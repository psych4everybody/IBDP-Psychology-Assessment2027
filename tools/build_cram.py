#!/usr/bin/env python3
"""Build assets/bank-cram.js, the card data for cram.html that is not already in a bank file.

Usage (from the repo root): python3 tools/build_cram.py

It collects two things that live in other parts of the site:
  - TERMS: every content term and research methodology term in tools/content_terms.json,
    with its definition, the contexts of the chapters that teach or use it, and links;
  - STUDIES: every key study table in the worksheet chapters (a table whose first row is
    "Aim"), with its aim, findings, conclusion, "Use it for" and "Evaluate it with" rows.
The other cards (Paper 1 Sections A to C, Paper 2 practicals, Paper 3 figures) are built in
the browser by assets/cram.js from bank-p1.js, bank-p2.js, bank-p3.js and p3.js.

Run it again after changing content_terms.json or rebuilding any chapter page, then commit
assets/bank-cram.js. Running it twice changes nothing.
"""
import glob
import html
import json
import os
import re

from bs4 import BeautifulSoup

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = json.load(open(os.path.join(ROOT, "tools", "content_terms.json"), encoding="utf-8"))

CONTEXTS = {"CRM": "fd", "CL": "lc", "HD": "hd", "HW": "hw", "HR": "hr"}
CONCEPTS = ["bias", "causality", "change", "measurement", "perspective", "responsibility"]
KEEP = {"b", "strong", "i", "em", "sub", "sup", "br"}


def ctx_of(code):
    return CONTEXTS[code.split("-")[0]]


def href(ref):
    code, _, anchor = ref.partition("#")
    return "ws-" + code.lower() + ".html" + ("#" + anchor if anchor else "")


def clean(cell):
    """Inner HTML of a table cell, keeping only simple inline tags."""
    s = cell.decode_contents()
    s = re.sub(r"<(/?)([a-zA-Z0-9]+)[^>]*>", lambda m: m.group(0) if m.group(2).lower() in KEEP else "", s)
    s = re.sub(r"<(/?)(b|strong|i|em|sub|sup)\s[^>]*>", r"<\1\2>", s)
    return re.sub(r"\s+", " ", s).strip()


def text(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s))).strip()


# ---------- chapters and key studies ----------
chapters, studies = {}, []
for f in sorted(glob.glob(os.path.join(ROOT, "ws-*.html"))):
    page = os.path.basename(f)
    code = page[3:-5].upper()
    soup = BeautifulSoup(open(f, encoding="utf-8").read(), "html.parser")
    h1 = soup.select_one("header h1")
    chapters[code] = h1.get_text(" ", strip=True) if h1 else code
    for card in soup.select("section.card[id]"):
        table = card.select_one("table")
        if not table:
            continue
        rows = []
        for tr in table.select("tr"):
            cells = tr.find_all("td", recursive=False)
            if len(cells) == 2 and "key" in (cells[0].get("class") or []):
                rows.append((cells[0].get_text(" ", strip=True), clean(cells[1])))
        if not rows or rows[0][0] != "Aim":
            continue
        r = dict(rows)
        find = [v for k, v in rows if k.startswith("Findings")]
        if not find:
            find = [f"<b>{html.escape(k)}:</b> {v}" for k, v in rows if k.startswith("Experiment")]
        use, ev = r.get("Use it for", ""), r.get("Evaluate it with", "")
        if not find or not use:
            continue  # a practical write-up or a design table, not a key study
        h2 = card.select_one("h2")
        title = re.sub(r"^Key study( \d+)?:\s*", "", h2.get_text(" ", strip=True) if h2 else card.get("data-toc", ""))
        title = title[:1].upper() + title[1:]
        if title.startswith("The study used in the workout"):
            continue  # a repeat of a key study taught in full elsewhere
        concepts = sorted({c for c in CONCEPTS if re.search(r"<b>\s*" + c + r"\s*:", ev, re.I)})
        studies.append({
            "id": "st-" + code.lower() + "-" + card["id"],
            "title": title, "code": code, "ctx": ctx_of(code), "href": page + "#" + card["id"],
            "aim": r["Aim"], "find": find, "concl": r.get("Conclusion", ""),
            "use": use, "ev": ev, "concepts": concepts,
        })

# ---------- content terms ----------
terms = []
for t in DATA["terms"]:
    refs = t.get("learn", []) + t.get("also", [])
    ctxs = sorted({ctx_of(x.split("#")[0]) for x in refs if x.split("-")[0] in CONTEXTS})
    learn = t.get("learn", [])
    terms.append({
        "id": "tm-" + t["slug"], "slug": t["slug"], "name": t["name"], "group": t["group"],
        "bank": t.get("bank", ""), "def": t["def"], "ctx": ctxs,
        "learn": [{"href": href(x), "label": x.split("#")[0] + " " + chapters.get(x.split("#")[0], "")} for x in learn],
    })

out = {"chapters": chapters, "terms": terms, "studies": studies}
js = ("/* Cram mode cards drawn from the content terms and the worksheet key studies.\n"
      "   GENERATED by tools/build_cram.py: rebuild it, do not edit by hand. */\n"
      "window.CRAMBANK = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n")
open(os.path.join(ROOT, "assets", "bank-cram.js"), "w", encoding="utf-8").write(js)

missing = [s["title"] for s in studies if not s["concepts"]]
print(f"{len(terms)} terms, {len(studies)} key studies from {len(chapters)} chapters.")
if missing:
    print("No concept labels found in 'Evaluate it with' for:", "; ".join(missing))
