"""Build assets/bank-p3.js from data/paper3/sets-*.json.
Usage (from the repo root): python3 tools/validate_p3.py data/paper3/sets-*.json && python3 tools/build_bank_p3.py"""
import json, glob, os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXT_ORDER = ['Culture', 'Motivation', 'Technology']
CTX_ORDER = ['Health and well-being', 'Human development', 'Human relationships', 'Learning and cognition']

sets = []
for f in sorted(glob.glob(os.path.join(REPO, 'data/paper3/sets-*.json'))):
    d = json.load(open(f))
    sets += d['sets'] if isinstance(d, dict) else d
sets.sort(key=lambda s: (EXT_ORDER.index(s['extension']), CTX_ORDER.index(s['context'])))
for st in sets:
    for src in st['sources']:
        c = src.get('citation') or ''
        if c.startswith('Source: '): src['citation'] = c[len('Source: '):]
ids = [s['id'] for s in sets]
assert len(ids) == len(set(ids)), 'duplicate ids'

js = """/* Paper 3 practice sets. GENERATED by build_bank_p3.py from the reviewed set files: edit the JSON, not this file.
   Most sources are fictional; sources marked origin "adapted" summarise the published study in their citation. */
(function () {
  'use strict';
  var SETS = %s;
  function byId(id) { for (var i = 0; i < SETS.length; i++) if (SETS[i].id === id) return SETS[i]; return null; }
  function pickSet(id) { return byId(id) || SETS[Math.floor(Math.random() * SETS.length)]; }
  var LABEL = { 1: 'Question 1: interpretation of graphs', 2: 'Question 2: data analysis', 3: 'Question 3: research considerations', 4: 'Question 4: synthesis' };
  function q(set, n) {
    var x = set.questions[n - 1];
    return { type: 'P3', setId: set.id, n: n, label: LABEL[n], marks: x.marks, question: x.text, checklist: set.checklists['q' + n] };
  }
  function build(nums) { return function (id) { var s = pickSet(id); return nums.map(function (n) { return q(s, n); }); }; }
  var MODES = {
    full: { label: 'Full paper', minutes: 105, build: build([1, 2, 3, 4]),
      advice: 'Answer all four questions. Suggested times: about 40 minutes reading the sources and planning, 10 minutes each on questions 1 to 3, and 45 minutes on question 4.' },
    q13: { label: 'Questions 1 to 3', minutes: 50, build: build([1, 2, 3]),
      advice: 'Answer questions 1 to 3. Suggested times: about 20 minutes reading sources 1 to 3, then 10 minutes on each question.' },
    q4: { label: 'Question 4 only', minutes: 70, build: build([4]),
      advice: 'Answer question 4. Suggested times: about 25 minutes reading sources 2 to 5 and planning, then 45 minutes writing.' }
  };
  window.P3BANK = { SETS: SETS, byId: byId, MODES: MODES, paperName: 'Paper 3', totalMarks: 30 };
})();
""" % json.dumps(sets, ensure_ascii=False, indent=1)
open(os.path.join(REPO, 'assets/bank-p3.js'), 'w').write(js)
print(len(sets), 'sets ->', ', '.join(ids))
