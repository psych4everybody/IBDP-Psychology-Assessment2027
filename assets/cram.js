  // smart mix: weak and unseen cards first, then interleave the card types
  function deck(s) {
    var pool = matches(s);
    if (s.focus === 'weak') pool = pool.filter(function (c) { return hist[c.id] && hist[c.id][0] < 3; });
    var now = Date.now();
    var scored = pool.map(function (c) {
      var h = hist[c.id], sc;
      if (s.focus === 'random') sc = Math.random();
      else if (!h) sc = 2 + Math.random();
      else sc = (h[0] === 1 ? 3 : h[0] === 2 ? 2.4 : 0.6) + Math.min(1, (now - h[2]) / 6048e5) + Math.random() * 0.8;
      return { c: c, sc: sc };
    }).sort(function (a, b) { return b.sc - a.sc; }).slice(0, s.n);
    var buckets = {};
    scored.forEach(function (x) { (buckets[x.c.type] = buckets[x.c.type] || []).push(x.c.id); });
    var keys = shuffle(Object.keys(buckets)), out = [];
    while (out.length < scored.length) keys.forEach(function (k) { if (buckets[k].length) out.push(buckets[k].shift()); });
    return out;
  }

