  function rateCard(r) {
    var id = S.q[S.pos], x = S.res[id] || { first: r, tries: 0 };
    x.tries++; x.last = r; S.res[id] = x; rate(id, r);
    // Leitner-style repeats inside the session: "Not yet" comes back soon, "Partly" near the end
    if (r === 1 && x.tries < 3) S.q.splice(Math.min(S.q.length, S.pos + 4), 0, id);
    else if (r === 2 && x.tries < 2) S.q.push(id);
    S.pos++; store.set('session', S);
    if (S.pos >= S.q.length) finish(); else renderCard();
  }
  function finish() {
    clearInterval(timer); store.del('session');
    var ids = Object.keys(S.res), first = 0, later = 0, shaky = [];
    ids.forEach(function (id) { var x = S.res[id]; if (x.first === 3) first++; else if (x.last === 3) later++; else shaky.push(id); });
    var mins = Math.max(1, Math.round(minutes()));
    var h = '<div class="cr-score">' +
      '<div class="cr-stat s3"><b>' + first + '</b><span>Knew it first time</span></div>' +
      '<div class="cr-stat s2"><b>' + later + '</b><span>Got there on a retry</span></div>' +
      '<div class="cr-stat s1"><b>' + shaky.length + '</b><span>Still shaky</span></div></div>' +
      '<p class="small">' + ids.length + ' cards in about ' + mins + (mins === 1 ? ' minute' : ' minutes') + '.</p>';
    var byType = {};
    ids.forEach(function (id) { var t = BYID[id].type; byType[t] = byType[t] || [0, 0]; byType[t][1]++; if (S.res[id].first === 3) byType[t][0]++; });
    h += '<div class="cr-sub">By type of card (knew it first time)</div><div class="cr-bars">' + TYPES.filter(function (t) { return byType[t.key]; }).map(function (t) {
      var v = byType[t.key], p = Math.round(100 * v[0] / v[1]);
      return '<div class="cr-barrow"><span>' + t.name + '</span><div class="cr-bartrack"><div class="cr-barfill" style="width:' + p + '%"></div></div><b>' + v[0] + '/' + v[1] + '</b></div>';
    }).join('') + '</div>';
    if (shaky.length) {
      h += '<div class="cr-sub">Go back to these</div><ul class="cr-shaky">' + shaky.map(function (id) {
        var c = BYID[id], s = c.src[0];
        return '<li><span class="cr-type">' + esc(TYPE[c.type].name) + '</span> ' + esc(c.title.length > 120 ? c.title.slice(0, 117) + '...' : c.title) +
          (s ? ' <a href="' + esc(s.href) + '" target="_blank" rel="noopener">' + esc(s.label) + ' &#8599;</a>' : '') + '</li>';
      }).join('') + '</ul>';
    } else {
      h += '<div class="callout c-tip"><strong class="tag">Nice work</strong><p>Every card ended on "Knew it". Come back to a fresh mix in a day or two: spacing it out is what makes it stick.</p></div>';
    }
    $('doneBody').innerHTML = h;
    $('againBtn').hidden = !shaky.length;
    $('againBtn').onclick = function () { startSession(shuffle(shaky), 'Shaky cards'); };
    show('done'); mapHTML();
  }

  function show(name) {
    ['setup', 'session', 'done'].forEach(function (n) { $('screen-' + n).classList.toggle('active', n === name); });
    document.body.classList.toggle('cr-in-session', name === 'session');
    document.body.classList.toggle('cr-off-setup', name !== 'setup');
    window.scrollTo(0, 0);
  }

